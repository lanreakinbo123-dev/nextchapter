import jsPDF from "jspdf";

import { CvData, CvTemplateId } from "./cv-templates";

const PAGE_W = 595.28;
const PAGE_H = 841.89;
const M = 42;

// ₦ and → are not in WinAnsi — replace so they render in standard fonts
const clean = (t: string) => (t || "").replace(/₦/g, "NGN").replace(/→/g, "->");

function wrap(doc: jsPDF, text: string, width: number): string[] {
  return doc.splitTextToSize(clean(text), width) as string[];
}

/* ------------------------------------------------------------------ */
/* Plain text document (cover letters, personal statements, paste CV)  */
/* ------------------------------------------------------------------ */
function buildPlainDoc(
  title: string,
  content: string,
  theme: "emerald" | "classic" | "minimal" = "emerald"
) {
  const doc = new jsPDF({ orientation: "portrait", unit: "pt", format: "a4" });
  const maxWidth = PAGE_W - M * 2;
  let y = 50;

  if (theme === "emerald") {
    doc.setFillColor(5, 150, 105);
    doc.rect(0, 0, PAGE_W, 6, "F");
  } else if (theme === "classic") {
    doc.setFillColor(30, 41, 59);
    doc.rect(0, 0, PAGE_W, 6, "F");
  }

  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  if (theme === "emerald") doc.setTextColor(4, 120, 87);
  else doc.setTextColor(17, 24, 39);
  doc.text(clean(title), M, y);
  y += 24;

  doc.setDrawColor(229, 231, 235);
  doc.setLineWidth(0.75);
  doc.line(M, y, PAGE_W - M, y);
  y += 18;

  const lines = content.split("\n");

  for (const line of lines) {
    const trimmed = line.trim();

    if (y > PAGE_H - 50) {
      doc.addPage();
      y = 50;
      if (theme === "emerald") {
        doc.setFillColor(5, 150, 105);
        doc.rect(0, 0, PAGE_W, 4, "F");
      }
    }

    if (!trimmed) {
      y += 8;
      continue;
    }

    const isHeader =
      trimmed === trimmed.toUpperCase() &&
      trimmed.length > 3 &&
      !trimmed.includes("•") &&
      !trimmed.includes("|") &&
      trimmed.length < 50;

    if (isHeader) {
      y += 8;
      doc.setFont("helvetica", "bold");
      doc.setFontSize(11);
      if (theme === "emerald") doc.setTextColor(4, 120, 87);
      else doc.setTextColor(15, 23, 42);
      doc.text(clean(trimmed), M, y);
      y += 4;
      doc.setDrawColor(209, 213, 219);
      doc.setLineWidth(0.5);
      doc.line(M, y, M + 140, y);
      y += 14;
    } else if (trimmed.startsWith("•") || trimmed.startsWith("-")) {
      doc.setFont("helvetica", "normal");
      doc.setFontSize(9.5);
      doc.setTextColor(51, 65, 85);
      const wrapped = doc.splitTextToSize(clean(trimmed.replace(/^[•\-]\s*/, "")), maxWidth - 14) as string[];
      doc.setFillColor(16, 185, 129);
      doc.circle(M + 4, y - 3, 2, "F");
      doc.text(wrapped, M + 14, y);
      y += wrapped.length * 13 + 3;
    } else {
      doc.setFont("helvetica", "normal");
      doc.setFontSize(9.5);
      doc.setTextColor(51, 65, 85);
      const wrapped = doc.splitTextToSize(clean(trimmed), maxWidth) as string[];
      doc.text(wrapped, M, y);
      y += wrapped.length * 13 + 2;
    }
  }

  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFont("helvetica", "italic");
    doc.setFontSize(8);
    doc.setTextColor(156, 163, 175);
    doc.text(
      `Generated by Next Chapter AI (nextchapter.ng) • ATS Optimized • Page ${i} of ${totalPages}`,
      PAGE_W / 2,
      PAGE_H - 20,
      { align: "center" }
    );
  }

  return doc;
}

export function generatePdfDocument(
  title: string,
  content: string,
  theme: "emerald" | "classic" | "minimal" = "emerald"
) {
  const doc = buildPlainDoc(title, content, theme);
  const safeFilename = title.replace(/[^a-zA-Z0-9_\-\s]/g, "").replace(/\s+/g, "_");
  doc.save(`${safeFilename}.pdf`);
}

export function buildPlainPdfBuffer(
  title: string,
  content: string,
  theme: "emerald" | "classic" | "minimal" = "emerald"
): Buffer {
  return Buffer.from(buildPlainDoc(title, content, theme).output("arraybuffer"));
}


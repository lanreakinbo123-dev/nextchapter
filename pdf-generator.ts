function buildCvDoc(data: CvData, template: CvTemplateId) {
  const doc = new jsPDF({ orientation: "portrait", unit: "pt", format: "a4" });

  switch (template) {
    case "sidebar":
      renderSidebar(doc, data);
      break;
    case "navy":
      renderNavy(doc, data);
      break;
    case "serif":
      renderSerif(doc, data);
      break;
    case "banded":
      renderBanded(doc, data);
      break;
    case "clean":
      renderClean(doc, data);
      break;
    case "compact":
      renderCompact(doc, data);
      break;
  }

  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFont("helvetica", "italic");
    doc.setFontSize(7.5);
    doc.setTextColor(165, 168, 175);
    doc.text(
      `Generated by Next Chapter AI (nextchapter.ng) • ATS Optimized • Page ${i} of ${pages}`,
      PAGE_W / 2,
      PAGE_H - 18,
      { align: "center" }
    );
  }

  return doc;
}

export function generateCvPdf(data: CvData, template: CvTemplateId) {
  const doc = buildCvDoc(data, template);
  const safe = (data.fullName || "CV").replace(/[^a-zA-Z0-9_\-\s]/g, "").replace(/\s+/g, "_");
  doc.save(`${safe}_CV_${template}.pdf`);
}

export function buildCvPdfBuffer(data: CvData, template: CvTemplateId): Buffer {
  return Buffer.from(buildCvDoc(data, template).output("arraybuffer"));
}

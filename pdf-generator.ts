type RGB = [number, number, number];

function renderSidebar(doc: jsPDF, d: CvData) {
  const LX = M, LW = 146;
  const RX = M + 184, RW = PAGE_W - RX - M;
  const headerY = M + 34;
  let yL = 0, yR = 0;

  const paintBg = (top: number) => {
    doc.setFillColor(246, 247, 249);
    doc.rect(LX - 10, top, LW + 20, PAGE_H - top, "F");
  };

  doc.setFont("helvetica", "bold");
  doc.setFontSize(22);
  doc.setTextColor(70, 70, 78);
  doc.text(clean(d.fullName.toUpperCase()), PAGE_W / 2, headerY, { align: "center", charSpace: 3 });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(8.5);
  doc.setTextColor(130, 130, 140);
  doc.text(clean(d.title.toUpperCase()), PAGE_W / 2, headerY + 16, { align: "center", charSpace: 2 });
  doc.setDrawColor(190, 190, 198);
  doc.setLineWidth(0.8);
  doc.line(LX - 10, headerY + 28, PAGE_W - M + 10, headerY + 28);

  paintBg(headerY + 36);
  yL = headerY + 52;
  yR = headerY + 52;

  const ensureL = (n: number) => {
    if (yL + n > PAGE_H - 40) {
      doc.addPage();
      paintBg(8);
      yL = M + 10;
    }
  };
  const ensureR = (n: number) => {
    if (yR + n > PAGE_H - 40) {
      doc.addPage();
      paintBg(8);
      yR = M + 10;
    }
  };

  const headL = (t: string) => {
    ensureL(36);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8);
    doc.setTextColor(90, 90, 100);
    doc.text(clean(t), LX, yL, { charSpace: 1.5 });
    yL += 5;
    doc.setDrawColor(200, 200, 206);
    doc.setLineWidth(0.5);
    doc.line(LX, yL, LX + LW, yL);
    yL += 12;
  };
  const headR = (t: string) => {
    ensureR(30);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(8.5);
    doc.setTextColor(90, 90, 100);
    doc.text(clean(t), RX, yR, { charSpace: 1.5 });
    yR += 13;
  };
  const textL = (
    t: string,
    o: { bold?: boolean; size?: number; color?: RGB; gap?: number } = {}
  ) => {
    const size = o.size || 8;
    const lines = wrap(doc, t, LW);
    ensureL(lines.length * size + 6);
    doc.setFont("helvetica", o.bold ? "bold" : "normal");
    doc.setFontSize(size);
    if (o.color) doc.setTextColor(...o.color);
    else doc.setTextColor(85, 85, 95);
    lines.forEach((ln, i) => doc.text(ln, LX, yL + i * (size + 1.5)));
    yL += lines.length * (size + 1.5) + (o.gap ?? 4);
  };
  const bulletR = (t: string) => {
    const lines = wrap(doc, t, RW - 10);
    ensureR(lines.length * 10.5 + 6);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8.5);
    doc.setTextColor(140, 140, 150);
    doc.text("•", RX, yR);
    doc.setTextColor(80, 80, 90);
    lines.forEach((ln, i) => doc.text(ln, RX + 8, yR + i * 10.5));
    yR += lines.length * 10.5 + 2;
  };

  // LEFT column
  headL("Contact");
  [d.phone, d.email, d.website, d.location].forEach((c) => c && textL(c, { gap: 5 }));
  yL += 6;
  headL("Skills");
  d.skills.forEach((s) => textL(s, { gap: 3.5 }));
  yL += 6;
  headL("Education");
  d.education.forEach((e) => {
    textL(e.course, { bold: true, size: 8.5, gap: 1 });
    textL(e.institution, { bold: true, size: 8.5, gap: 1 });
    textL(e.period, { size: 7.5, color: [130, 130, 140], gap: 1 });
    if (e.qualification) textL(e.qualification, { size: 7.5, color: [110, 110, 120], gap: 5 });
  });
  yL += 4;
  headL("Certifications");
  d.certifications.forEach((c) => {
    textL(c.name, { bold: true, size: 8, gap: 0.5 });
    textL(c.org, { size: 7.5, gap: 0.5 });
    textL(c.period, { size: 7.5, color: [130, 130, 140], gap: 5 });
  });

  // RIGHT column
  headR("Profile");
  const profLines = wrap(doc, d.profile, RW);
  ensureR(profLines.length * 11 + 10);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(80, 80, 90);
  profLines.forEach((ln, i) => doc.text(ln, RX, yR + i * 11));
  yR += profLines.length * 11 + 10;
  headR("Work Experience");
  d.experience.forEach((j) => {
    ensureR(34);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9.5);
    doc.setTextColor(40, 40, 48);
    const tlines = wrap(doc, j.title, RW - 50);
    tlines.forEach((ln, i) => doc.text(ln, RX, yR + i * 10.5));
    yR += tlines.length * 10.5 + 1;
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(130, 130, 140);
    doc.text(clean(j.company), RX, yR);
    doc.text(clean(j.period), RX + RW, yR, { align: "right" });
    yR += 12;
    j.bullets.forEach((b) => bulletR(b));
    yR += 6;
  });
}


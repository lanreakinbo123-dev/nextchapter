import {
  AlignmentType,
  BorderStyle,
  Document,
  Paragraph,
  ShadingType,
  TabStopType,
  Table,
  TableCell,
  TableRow,
  TextRun,
  WidthType,
} from "docx";
import { CvData, CvTemplateId } from "./cv-templates";

/* ------------------------------------------------------------------ */
/* Plain text → .docx (cover letters, personal statements, paste CV)   */
/* ------------------------------------------------------------------ */
export async function createDocxBuffer(title: string, content: string): Promise<Buffer> {
  const lines = content.split("\n");
  const paragraphs: Paragraph[] = [];

  paragraphs.push(
    new Paragraph({
      text: title,
      spacing: { after: 200 },
      alignment: AlignmentType.CENTER,
      children: [new TextRun({ text: title, bold: true, size: 32, color: "047857" })],
    })
  );

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) {
      paragraphs.push(new Paragraph({ spacing: { after: 120 } }));
      continue;
    }
    const isHeader =
      trimmed === trimmed.toUpperCase() &&
      trimmed.length > 3 &&
      !trimmed.includes("•") &&
      !trimmed.includes("|") &&
      trimmed.length < 50;

    if (isHeader) {
      paragraphs.push(
        new Paragraph({
          spacing: { before: 240, after: 120 },
          children: [new TextRun({ text: trimmed, bold: true, size: 24, color: "107C41" })],
        })
      );
    } else if (trimmed.startsWith("•") || trimmed.startsWith("-")) {
      paragraphs.push(
        new Paragraph({
          bullet: { level: 0 },
          spacing: { after: 80 },
          children: [new TextRun({ text: trimmed.replace(/^[•\-]\s*/, ""), size: 21 })],
        })
      );
    } else {
      paragraphs.push(
        new Paragraph({
          spacing: { after: 100 },
          children: [new TextRun({ text: trimmed, size: 21 })],
        })
      );
    }
  }

  const doc = new Document({
    creator: "Next Chapter AI",
    title,
    description: "Career Document generated by Next Chapter for Nigerian Youth",
    sections: [
      {
        properties: {
          page: { margin: { top: 720, right: 720, bottom: 720, left: 720 } },
        },
        children: paragraphs,
      },
    ],
  });

  const { Packer } = await import("docx");
  return Packer.toBuffer(doc);
}

/* ================================================================== */
/* Template-aware CV → .docx                                            */
/* ================================================================== */

const NONE = { style: BorderStyle.NONE, size: 0, color: "FFFFFF" };
const NO_BORDERS = {
  top: NONE,
  bottom: NONE,
  left: NONE,
  right: NONE,
  insideHorizontal: NONE,
  insideVertical: NONE,
};

interface POpts {
  bold?: boolean;
  size?: number;
  color?: string;
  italic?: boolean;
  align?: (typeof AlignmentType)[keyof typeof AlignmentType];
  before?: number;
  after?: number;
  charSpacing?: number;
  font?: string;
}

const p = (text: string, o: POpts = {}) =>
  new Paragraph({
    alignment: o.align,
    spacing: { before: o.before ?? 0, after: o.after ?? 60 },
    children: [
      new TextRun({
        text,
        bold: o.bold,
        italics: o.italic,
        size: Math.round((o.size ?? 10) * 2),
        color: o.color ?? "1F2937",
        characterSpacing: o.charSpacing ?? 0,
        font: o.font,
      }),
    ],
  });

const bullet = (text: string, o: POpts = {}) =>
  new Paragraph({
    bullet: { level: 0 },
    spacing: { after: o.after ?? 40 },
    children: [
      new TextRun({
        text,
        size: Math.round((o.size ?? 9.5) * 2),
        color: o.color ?? "374151",
        italics: o.italic,
      }),
    ],
  });

const heading = (t: string, accent = "059669") =>
  new Paragraph({
    spacing: { before: 220, after: 120 },
    border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: accent } },
    children: [
      new TextRun({
        text: t.toUpperCase(),
        bold: true,
        size: 19,
        characterSpacing: 120,
        color: "111827",
      }),
    ],
  });

const band = (t: string) =>
  new Paragraph({
    shading: { type: ShadingType.CLEAR, fill: "E7E9EA" },
    spacing: { before: 240, after: 120 },
    children: [
      new TextRun({
        text: t,
        bold: true,
        size: 16,
        characterSpacing: 140,
        color: "4B5563",
      }),
    ],
  });

const sideHead = (t: string) =>
  new Paragraph({
    spacing: { before: 200, after: 80 },
    children: [
      new TextRun({
        text: t.toUpperCase(),
        bold: true,
        size: 16,
        characterSpacing: 160,
        color: "6B7280",
      }),
    ],
  });

const contactList = (d: CvData) =>
  [d.phone, d.email, d.website, d.location].filter(Boolean).map((c) =>
    p(c, { size: 9, color: "4B5563", after: 60 })
  );

const skillList = (d: CvData) =>
  d.skills.map((s) => p(s, { size: 9, color: "4B5563", after: 50 }));

const jobParas = (
  j: CvData["experience"][number],
  o: { rightPeriod?: boolean; italicCompany?: boolean } = {}
) => {
  const out: Paragraph[] = [];
  out.push(
    new Paragraph({
      spacing: { before: 140, after: 20 },
      tabStops: o.rightPeriod
        ? [{ type: TabStopType.RIGHT, position: 10460 }]
        : undefined,
      children: [
        new TextRun({ text: j.title, bold: true, size: 20, color: "111827" }),
        ...(o.rightPeriod
          ? [new TextRun({ text: "\t" + j.period, size: 16, bold: true, color: "6B7280" })]
          : []),
      ],
    })
  );
  out.push(p(j.company, { size: 9.5, italic: o.italicCompany, color: "4B5563", after: 60 }));
  if (!o.rightPeriod && j.period) out.push(p(j.period, { size: 8.5, color: "6B7280", after: 60 }));
  j.bullets.forEach((b) => out.push(bullet(b, { size: 9.5 })));
  return out;
};

const eduParas = (d: CvData, o: { boldInst?: boolean } = {}) =>
  d.education.flatMap((e) => [
    p([e.qualification, e.course].filter(Boolean).join(" — "), { bold: true, size: 9.5, after: 20 }),
    p(e.institution, { bold: o.boldInst, size: 9.5, color: "374151", after: 20 }),
    p(e.period, { size: 8.5, color: "6B7280", after: 120 }),
  ]);

const certParas = (d: CvData, size = 9) =>
  d.certifications.flatMap((c) => [
    p(c.name, { bold: true, size, after: 10 }),
    p(c.org + (c.period ? "  —  " + c.period : ""), { size: size - 1, color: "6B7280", after: 90 }),
  ]);

const twoCol = (
  left: Paragraph[],
  right: Paragraph[],
  leftPct = 34,
  leftFill?: string
) =>
  new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    borders: NO_BORDERS,
    rows: [
      new TableRow({
        children: [
          new TableCell({
            width: { size: leftPct, type: WidthType.PERCENTAGE },
            shading: leftFill ? { type: ShadingType.CLEAR, fill: leftFill } : undefined,
            margins: { top: 120, bottom: 120, left: 160, right: 160 },
            children: left,
          }),
          new TableCell({
            width: { size: 100 - leftPct, type: WidthType.PERCENTAGE },
            margins: { top: 120, bottom: 120, left: 160, right: 160 },
            children: right,
          }),
        ],
      }),
    ],
  });

export async function createCvDocx(data: CvData, template: CvTemplateId): Promise<Buffer> {
  const children: (Paragraph | Table)[] = [];
  const emptyPara = p(" ", { size: 8 });

  switch (template) {
    case "sidebar": {
      children.push(p(data.fullName.toUpperCase(), { align: AlignmentType.CENTER, bold: true, size: 19, charSpacing: 200, color: "44464E", after: 60 }));
      children.push(p(data.title.toUpperCase(), { align: AlignmentType.CENTER, size: 9, charSpacing: 180, color: "9CA3AF", after: 240 }));
      children.push(
        twoCol(
          [
            sideHead("Contact"),
            ...contactList(data),
            sideHead("Skills"),
            ...skillList(data),
            sideHead("Education"),
            ...eduParas(data, { boldInst: true }),
            sideHead("Certifications"),
            ...certParas(data),
          ],
          [
            sideHead("Profile"),
            p(data.profile, { size: 9.5, after: 140 }),
            sideHead("Work Experience"),
            ...data.experience.flatMap((j) => jobParas(j, { rightPeriod: true })),
          ],
          34,
          "F5F6F8"
        )
      );
      break;
    }
    case "navy": {
      children.push(
        new Table({
          width: { size: 100, type: WidthType.PERCENTAGE },
          borders: NO_BORDERS,
          rows: [
            new TableRow({
              children: [
                new TableCell({
                  shading: { type: ShadingType.CLEAR, fill: "17304C" },
                  margins: { top: 320, bottom: 320, left: 200, right: 200 },
                  children: [
                    p(data.fullName.toUpperCase(), { align: AlignmentType.CENTER, bold: true, size: 20, color: "FFFFFF", charSpacing: 220, after: 60 }),
                    p(data.title.toUpperCase(), { align: AlignmentType.CENTER, size: 9, color: "D9B45B", charSpacing: 220 }),
                  ],
                }),
              ],
            }),
          ],
        })
      );
      children.push(
        twoCol(
          [
            sideHead("Contact"),
            ...contactList(data),
            sideHead("Skills"),
            ...skillList(data),
            sideHead("Education"),
            ...eduParas(data),
            sideHead("Certifications"),
            ...certParas(data),
          ],
          [
            sideHead("Summary"),
            p(data.profile, { size: 9.5, after: 140 }),
            sideHead("Professional Experience"),
            ...data.experience.flatMap((j) => jobParas(j, { rightPeriod: true, italicCompany: true })),
          ],
          33
        )
      );
      break;
    }
    case "serif": {
      children.push(p(data.fullName.toUpperCase(), { align: AlignmentType.CENTER, font: "Georgia", size: 22, charSpacing: 300, color: "23252B", after: 80 }));
      children.push(
        new Paragraph({
          border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: "D1D5DB" } },
          spacing: { after: 260 },
          children: [],
        })
      );
      children.push(
        twoCol(
          [
            sideHead("Contact"),
            ...contactList(data),
            sideHead("Education"),
            ...eduParas(data, { boldInst: true }),
            sideHead("Skills"),
            ...data.skills.map((s) => p("» " + s, { size: 9, color: "4B5563", after: 50 })),
            sideHead("Certification"),
            ...certParas(data),
          ],
          [
            sideHead("About Me"),
            p(data.profile, { size: 9.5, after: 140 }),
            sideHead("Work Experience"),
            ...data.experience.flatMap((j) => jobParas(j, { rightPeriod: true })),
          ],
          40
        )
      );
      break;
    }
    case "banded": {
      children.push(p(data.fullName.toUpperCase(), { align: AlignmentType.CENTER, size: 18, charSpacing: 300, color: "6B7280", after: 40 }));
      children.push(p(data.title.toUpperCase(), { align: AlignmentType.CENTER, size: 9, charSpacing: 200, color: "9CA3AF", after: 260 }));

      children.push(band("Contact Info"));
      children.push(
        twoCol(
          [data.phone, data.email].filter(Boolean).map((c) => p(c, { size: 9.5, color: "4B5563", after: 60 })),
          [data.location, data.website].filter(Boolean).map((c) => p(c, { size: 9.5, color: "4B5563", after: 60 })),
          50
        )
      );

      children.push(band("Profile"));
      children.push(p(data.profile, { size: 9.5 }));

      children.push(band("Experience"));
      const leftJobs = data.experience.filter((_, i) => i % 2 === 0);
      const rightJobs = data.experience.filter((_, i) => i % 2 === 1);
      children.push(
        twoCol(
          leftJobs.length ? leftJobs.flatMap((j) => jobParas(j)) : [emptyPara],
          rightJobs.length ? rightJobs.flatMap((j) => jobParas(j)) : [emptyPara],
          50
        )
      );

      children.push(
        new Table({
          width: { size: 100, type: WidthType.PERCENTAGE },
          borders: NO_BORDERS,
          rows: [
            new TableRow({
              children: [
                new TableCell({
                  width: { size: 50, type: WidthType.PERCENTAGE },
                  margins: { left: 0, right: 80 },
                  children: [band("Education"), ...eduParas(data)],
                }),
                new TableCell({
                  width: { size: 50, type: WidthType.PERCENTAGE },
                  margins: { left: 80, right: 0 },
                  children: [
                    band("Skill"),
                    ...data.skills.map((s) => bullet(s, { size: 9.5 })),
                  ],
                }),
              ],
            }),
          ],
        })
      );
      break;
    }
    case "clean": {
      children.push(p(data.fullName, { bold: true, size: 18, color: "14161A", after: 40 }));
      children.push(p(data.title.toUpperCase(), { bold: true, size: 9, color: "059669", charSpacing: 100, after: 60 }));
      children.push(p([data.phone, data.email, data.location].filter(Boolean).join("   •   "), { size: 8.5, color: "7A7D85", after: 180 }));
      children.push(heading("Profile"));
      children.push(p(data.profile, { size: 9.5 }));
      children.push(heading("Core Skills"));
      data.skills.forEach((s) => children.push(bullet(s)));
      children.push(heading("Work Experience"));
      data.experience.forEach((j) => children.push(...jobParas(j, { rightPeriod: true })));
      children.push(heading("Education"));
      children.push(...eduParas(data));
      children.push(heading("Certifications"));
      children.push(...certParas(data, 9.5));
      break;
    }
    case "compact": {
      children.push(
        new Paragraph({
          border: { top: { style: BorderStyle.SINGLE, size: 24, color: "059669", space: 4 } },
          spacing: { after: 40 },
          children: [new TextRun({ text: data.fullName, bold: true, size: 32, color: "14161A" })],
        })
      );
      children.push(p(data.title.toUpperCase(), { bold: true, size: 8.5, color: "059669", charSpacing: 120, after: 60 }));
      children.push(p([data.phone, data.email, data.location].filter(Boolean).join("  |  "), { size: 8, color: "7A7D85", after: 160 }));

      const cHead = (t: string) =>
        new Paragraph({
          spacing: { before: 160, after: 80 },
          children: [
            new TextRun({ text: "▪  ", bold: true, size: 18, color: "059669" }),
            new TextRun({ text: t.toUpperCase(), bold: true, size: 15, characterSpacing: 100, color: "23252B" }),
          ],
        });

      children.push(cHead("Profile"));
      children.push(p(data.profile, { size: 9 }));
      children.push(cHead("Core Skills"));
      data.skills.forEach((s) => children.push(bullet(s, { size: 9, after: 30 })));
      children.push(cHead("Work Experience"));
      data.experience.forEach((j) => children.push(...jobParas(j, { rightPeriod: true })));
      children.push(cHead("Education"));
      children.push(...eduParas(data));
      children.push(cHead("Certifications"));
      children.push(...certParas(data, 9));
      break;
    }
  }

  const doc = new Document({
    creator: "Next Chapter AI",
    title: `${data.fullName} - CV (${template})`,
    description: "ATS-optimized CV generated by Next Chapter for Nigerian Youth",
    sections: [
      {
        properties: {
          page: { margin: { top: 720, right: 720, bottom: 720, left: 720 } },
        },
        children,
      },
    ],
  });

  const { Packer } = await import("docx");
  return Packer.toBuffer(doc);
}
